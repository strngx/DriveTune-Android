export function renderPlaylistCard(playlist) {
  const images = playlist.covers || [];
  const collageItems = [0, 1, 2, 3].map(idx => {
    const src = images[idx] || 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=200&q=80';
    return `<img src="${src}" class="playlist-collage-item" alt="Cover" loading="lazy">`;
  }).join('');

  return `
    <div class="playlist-card" data-playlist-id="${playlist.id}">
      <div class="playlist-collage">
        ${collageItems}
      </div>
      <div class="playlist-card-title">${playlist.title}</div>
      <div class="playlist-card-tracks">${playlist.trackIds.length} tracks • Offline</div>
    </div>
  `;
}


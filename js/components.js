export function renderTrackRow(track, options = {}) {
  const {
    isPlaying = false,
    isSelected = false,
    showCheckbox = false,
    showDuration = true,
    showStatusBadge = true,
    context = 'library'
  } = options;

  let statusIcon = '';
  if (track.status === 'downloaded') {
    statusIcon = `<span class="status-icon downloaded" title="Available Offline (Stored Locally)">${Icons.downloaded}</span>`;
  } else if (track.status === 'downloading') {
    statusIcon = `<span class="status-icon downloading" title="Downloading ${track.progress}%">${Icons.downloading}</span>`;
  } else if (track.status === 'cloud') {
    statusIcon = `<span class="status-icon cloud" title="Available in Google Drive">${Icons.cloud}</span>`;
  }

  const checkboxHtml = showCheckbox ? `
    <div class="track-select-box" style="margin-right: 8px;">
      <input type="checkbox" data-track-id="${track.id}" class="track-checkbox" ${isSelected ? 'checked' : ''} style="accent-color: var(--accent-primary); width: 18px; height: 18px; cursor: pointer;">
    </div>
  ` : '';

  const equalizerHtml = isPlaying ? `
    <div class="playing-equalizer">
      <div class="eq-bar"></div>
      <div class="eq-bar"></div>
      <div class="eq-bar"></div>
    </div>
  ` : '';

  return `
    <div class="track-row ${isPlaying ? 'is-playing' : ''} ${isSelected ? 'is-selected' : ''}" 
         data-track-id="${track.id}" 
         data-context="${context}">
      ${checkboxHtml}
      
      <div class="track-thumb-wrap">
        <img src="${track.coverArt}" alt="${track.title}" class="track-thumb" loading="lazy">
        <div class="track-play-overlay">
          ${isPlaying ? Icons.pause : Icons.play}
        </div>
      </div>

      <div class="track-info">
        <div class="track-title">${track.title}</div>
        <div class="track-meta">
          <span class="track-artist">${track.artist}</span>
          <span>•</span>
          <span class="badge-format">${track.format}</span>
          ${track.status === 'downloaded' ? `<span class="mini-offline-badge">OFFLINE</span>` : ''}
        </div>
      </div>

      <div class="track-actions">
        ${equalizerHtml}
        ${showStatusBadge ? statusIcon : ''}
        ${showDuration ? `<span class="track-duration">${track.durationStr}</span>` : ''}
        <button class="btn-icon btn-track-menu" data-track-id="${track.id}" title="Track Options">
          ${Icons.more}
        </button>
      </div>
    </div>
  `;
}

